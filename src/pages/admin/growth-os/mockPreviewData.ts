export function formatDemoMoneyCents(cents: number, currency: GrowthOsCurrency): string {
  const major = cents / 100;
  const locale = currency === 'BRL' ? 'pt-BR' : currency === 'EUR' ? 'pt-PT' : 'en-US';
  return new Intl.NumberFormat(locale, {
    style: 'currency',
    currency,
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  }).format(major);
}

export const formatCents = formatDemoMoneyCents;

